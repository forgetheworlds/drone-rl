"""Build results/LEADERBOARD.md (test) or LEADERBOARD_<split>.md from results/<split>_<profile>.jsonl
(latest run per method wins).

  python leaderboard.py [--results DIR] [--split test|nav]

Headline (runs with nav metrics): stop_cost = 100*(10*FF<1.5m + 10*FF inside the 1 m/s stopping
distance + unknown inside it + 3*false-occupied <3 m), obstacle rays only, lower is better.
Legacy: planner_cost = 100*(10*FF<1.5m + 3*false-occ + unknown), all rays.
"""
import argparse
import glob
import json
import os

PROFILE_ORDER = ["ov2640", "clean", "ov2640_dark", "ov2640_unsync", "ov2640_dots"]
BASELINE = "sgbm320"
COLS = [  # (header, key, fmt)
    ("cost", "planner_cost", "{:.0f}"),
    ("ray FF<1.5m", "ray_false_free_near", "{:.1%}"),
    ("ray FF all", "ray_false_free", "{:.1%}"),
    ("ray false-occ", "ray_false_occ", "{:.1%}"),
    ("ray unknown", "ray_unknown", "{:.0%}"),
    ("free cov", "free_coverage", "{:.0%}"),
    ("px holes", "px_hole", "{:.0%}"),
    ("px false-near", "px_false_near", "{:.1%}"),
    ("<1m valid", "valid_0.2-1", "{:.0%}"),
    ("<1m ok", "ok_0.2-1", "{:.0%}"),
    ("textureless holes", "hole_textureless", "{:.0%}"),
    ("thin det", "thin_ray_detected", "{:.0%}"),
    ("vox occ IoU", "vox_occ_iou", "{:.2f}"),
    ("vox free IoU", "vox_free_iou", "{:.2f}"),
    ("vox FF<1m /seq", "vox_false_free_1m_per_seq", "{:.1f}"),
    ("k (σ/z²)", "k_sigma_over_z2", "{:.3f}"),
    ("box ms", "ms_box", "{:.1f}"),
    ("Zero2W ms", ("est_ms", "pi_zero2w_1core"), "{:.0f}"),
    ("P4 ms", ("est_ms", "esp32p4_1core"), "{:.0f}"),
]

NAV_COLS = [
    ("stop cost", "stop_cost", "{:.0f}"),
    ("FF<1.5m", "nav_ff_1.5", "{:.1%}"),
    ("FF<1.5m solid", "nav_ff_1.5_solid", "{:.1%}"),
    ("stop@1 FF", "stop1_ff", "{:.1%}"),
    ("stop@1 unk", "stop1_unknown", "{:.0%}"),
    ("stop@2 FF", "stop2_ff", "{:.1%}"),
    ("stop@2 unk", "stop2_unknown", "{:.0%}"),
    ("false-occ<3m", "nav_fo_3m", "{:.1%}"),
    ("unknown", "nav_unknown", "{:.0%}"),
    ("unk: textureless", "unk_textureless", "{:.0%}"),
    ("unk: beyond 3m", "unk_beyond_range", "{:.1%}"),
    ("unk: occl/other", "unk_occluded_other", "{:.1%}"),
    ("unk 0-1m", "unk_band_0-1", "{:.0%}"),
    ("unk 1-2m", "unk_band_1-2", "{:.0%}"),
    ("unk 2-3m", "unk_band_2-3", "{:.0%}"),
    ("unk 3-5m", "unk_band_3-5", "{:.0%}"),
    ("far-free", "nav_far_free", "{:.0%}"),
    ("thin seen", "nav_thin_detected", "{:.0%}"),
    ("vox FF<1m /seq", "vox_false_free_1m_per_seq", "{:.1f}"),
    ("vox occ IoU", "vox_occ_iou", "{:.2f}"),
    ("vox free IoU", "vox_free_iou", "{:.2f}"),
    ("box ms", "ms_box", "{:.1f}"),
    ("Zero2W ms", ("est_ms", "pi_zero2w_1core"), "{:.0f}"),
    ("P4 ms", ("est_ms", "esp32p4_1core"), "{:.0f}"),
]


def get(r, key):
    if isinstance(key, tuple):
        r = r.get(key[0], {}); key = key[1]
    return r.get(key)


def table(rows, cols=COLS, sort="planner_cost"):
    out = ["| method | " + " | ".join(c[0] for c in cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for r in sorted(rows, key=lambda r: r[sort]):
        cells = []
        for _, key, fmt in cols:
            v = get(r, key)
            cells.append("–" if v is None or v != v else fmt.format(v))
        name = f"**{r['method']}** (baseline)" if r["method"] == BASELINE else r["method"]
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--results", default=os.path.join(here, "results"))
    ap.add_argument("--split", default="test")
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.results, f"{a.split}_*.jsonl")))
    by_prof = {}
    for fn in files:
        for line in open(fn):
            r = json.loads(line)
            # Section label from the file name (test_ov2640_dark.jsonl -> ov2640_dark), so runs on
            # other data with the same camera profile (nav_ov2640_retex0.3.jsonl) get their own section.
            label = os.path.basename(fn)[len(a.split) + 1:-len(".jsonl")]
            by_prof.setdefault(label, {})[r["method"]] = r
    profs = [p for p in PROFILE_ORDER if p in by_prof] + sorted(set(by_prof) - set(PROFILE_ORDER))
    md = [f"# Depth benchmark leaderboard ({a.split} split)", "",
          "Generated by `leaderboard.py`; see README.md for metric definitions. Lower `cost` is better:",
          "`cost = 100*(10*FF<1.5m + 3*false-occ + unknown)` over 16x12 ray blocks. FF = false-free (ray says free",
          "where GT is occupied: the dangerous error). Runtimes: single-thread on the box, scaled to Pi Zero 2 W",
          "and ESP32-P4 cores with rough factors (10x, 30x); not measured on target.", ""]
    notes = {}
    for p in profs:
        rows = list(by_prof[p].values())
        n = rows[0]
        md += [f"## profile `{p}`  ({n['seqs']} sequences, {n['frames']} frames)", ""]
        nav = [r for r in rows if "stop_cost" in r]
        if nav:
            md += ["### Navigation view: errors inside the stopping distance (headline)", "",
                   "Obstacle rays only (floor and ceiling excluded). `stop@v` = rays whose obstacle is inside",
                   "d_stop(v) = 0.3 + 0.4v + v^2/3 (1.03 m at 1 m/s, 2.43 m at 2 m/s). `unk:` columns split all",
                   "unknown rays by cause (share of all rays); `unk a-b m` = unknown rate of rays whose true depth",
                   "is in that band. `far-free` = matched beyond the 3 m cap (known free to 3 m).", "",
                   table(nav, NAV_COLS, "stop_cost"), "", "### Legacy metrics (all rays)", ""]
        md += [table(rows), ""]
        if "retex" in p:
            md += ["_Retextured renders (`retexture.py`): world-anchored 3-octave value-noise albedo, amp "
                   + p.split("retex")[1].split("_")[0] + ", clean images (no rolling shutter or blur). amp 0.3 matches"
                   " real indoor photos in gradient energy but has almost no textureless area and ~1/6 of the"
                   " real SGBM phantom rate, so it is optimistic; see the real-photo table below._", ""]
        for r in rows:
            notes[r["method"]] = r.get("note", "")
    cal = os.path.join(a.results, "preset_calibration.json")
    if a.split == "nav" and os.path.exists(cal):
        sweep = json.load(open(cal)).get("real_method_sweep", {})
        md += ["## Real indoor photos (ETH3D indoor + Middlebury, rescaled to the drone pair, `ov2640`)", "",
               "Ray level (same blocks), GT < 3 m, from `calibrate_preset.py`. `photo cost` = 100*(10*FF<1.5m*(1-hole) +",
               "3*phantom + hole), the legacy cost on these rates (FF here is per returned ray, so it is scaled by the",
               "return rate). Small sample (31 pairs, 3257 rays); no stop-distance split.", "",
               "| method | photo cost | hole | hole textured | hole textureless | phantom | phantom textureless | phantom blob (rays) | FF<1.5m (of returns) | k |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        def pc(r):
            return 100 * (10 * r["false_free"] * (1 - r["hole_all"]) + 3 * r["phantom"] + r["hole_all"])
        for m, r in sorted(sweep.items(), key=lambda kv: pc(kv[1])):
            md.append(f"| `{m}` | {pc(r):.0f} | {r['hole_all']:.1%} | {r['hole_textured']:.1%} | {r['hole_textureless']:.1%}"
                      f" | {r['phantom']:.1%} | {r['phantom_textureless']:.1%} | {r.get('phantom_blob_rays') or 0:.1f}"
                      f" | {r['false_free']:.1%} | {r['k']:.3f} |")
        md.append("")
    md += ["## Methods", ""] + [f"- `{k}`: {v}" for k, v in sorted(notes.items())] + [""]
    path = os.path.join(a.results, "LEADERBOARD.md" if a.split == "test" else f"LEADERBOARD_{a.split}.md")
    open(path, "w").write("\n".join(md))
    print(path)


if __name__ == "__main__":
    main()
