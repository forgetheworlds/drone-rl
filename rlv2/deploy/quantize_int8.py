"""Int8 weight quantization of an rlv2 checkpoint (per-output-channel symmetric, biases kept fp32).

  python quantize_int8.py IN.bin OUT_fakequant.bin [OUT_int8.h]

OUT_fakequant.bin: same format with weights rounded to the int8 grid (grade it to see the accuracy cost).
OUT_int8.h: C arrays (int8 weights, float scales, float biases, normalizer) for the ESP32-P4 runtime.
Only the first net (the actor) is exported to the header.
"""
import struct, sys
import numpy as np

src, dst = sys.argv[1], sys.argv[2]
hdr = sys.argv[3] if len(sys.argv) > 3 else ""
b = bytearray(open(src, "rb").read())
magic, count = struct.unpack_from("<II", b, 0)
assert magic == 0x32564C52
o = 8; nets = []
for n in range(count):
    L = struct.unpack_from("<I", b, o)[0]; o += 4
    sizes = struct.unpack_from(f"<{L}i", b, o); o += 4 * L
    act = struct.unpack_from("<I", b, o)[0]; o += 4
    layers = []
    for l in range(L - 1):
        i, j = sizes[l], sizes[l + 1]
        W = np.frombuffer(b, np.float32, i * j, o).reshape(j, i).copy()
        s = np.abs(W).max(1) / 127 + 1e-12
        q = np.clip(np.round(W / s[:, None]), -127, 127).astype(np.int8)
        b[o:o + 4 * i * j] = (q.astype(np.float32) * s[:, None]).astype(np.float32).tobytes()
        bias = np.frombuffer(b, np.float32, j, o + 4 * i * j).copy()
        layers.append((q, s, bias)); o += 4 * (i * j + j)
    nets.append((sizes, act, layers))
dims = struct.unpack_from("<I", b, o)[0]; o += 4
mean = np.frombuffer(b, np.float64, dims, o); var = np.frombuffer(b, np.float64, dims, o + 8 * dims)
open(dst, "wb").write(b)
sizes, act, layers = nets[0]
nparam = sum(q.size for q, _, _ in layers); nbias = sum(len(x) for _, _, x in layers)
print(f"actor {sizes} act={act}: {nparam} weights -> {nparam} B int8 + {4 * (nbias + sum(len(s) for _, s, _ in layers))} B scales/biases"
      f" + {8 * dims} B normalizer (fp32); MACs/inference {nparam}")
if hdr:
    with open(hdr, "w") as f:
        f.write("// generated by rlv2/deploy/quantize_int8.py; actor only\n#pragma once\n#include <stdint.h>\n")
        f.write(f"#define POLICY_LAYERS {len(layers)}\nstatic const int policy_sizes[] = {{{', '.join(map(str, sizes))}}};\n")
        f.write(f"static const int policy_tanh = {1 if act == 0 else 0};\n")
        for l, (q, s, bias) in enumerate(layers):
            f.write(f"static const int8_t policy_w{l}[] = {{{', '.join(map(str, q.ravel().tolist()))}}};\n")
            f.write(f"static const float policy_s{l}[] = {{{', '.join(f'{x:.8g}f' for x in s)}}};\n")
            f.write(f"static const float policy_b{l}[] = {{{', '.join(f'{x:.8g}f' for x in bias)}}};\n")
        f.write(f"static const float policy_mean[] = {{{', '.join(f'{x:.8g}f' for x in mean)}}};\n")
        f.write(f"static const float policy_inv_std[] = {{{', '.join(f'{1 / np.sqrt(x + 1e-8):.8g}f' for x in var)}}};\n")
